"""
Patient management API endpoints.
Enforces data minimisation, pseudonymisation, and strict RBAC controls.
"""
from __future__ import annotations

import secrets
import uuid
from datetime import date, datetime, timezone
from typing import Any

from fastapi import APIRouter, Depends, HTTPException, Query, Request, Response, status
from pydantic import BaseModel, Field
from sqlalchemy import func, or_, select
from sqlalchemy.ext.asyncio import AsyncSession
from sqlalchemy.orm import selectinload

from app.db.session import get_db
from app.models.patient import Patient
from app.models.sample import Sample
from app.security.dependencies import CurrentUser, require_permission
from app.services.audit import record_audit_event

router = APIRouter()


class PatientCreate(BaseModel):
    patient_code: str | None = Field(None, description="Optional custom identifier; autogenerated if omitted.")
    date_of_birth: date | None = None
    biological_sex: str | None = Field(None, pattern="^(male|female|intersex|not_specified)$")
    first_name: str | None = None
    last_name: str | None = None
    notes: str | None = None
    is_synthetic: bool = True


class PatientUpdate(BaseModel):
    date_of_birth: date | None = None
    biological_sex: str | None = Field(None, pattern="^(male|female|intersex|not_specified)$")
    first_name: str | None = None
    last_name: str | None = None
    notes: str | None = None


class PatientResponse(BaseModel):
    id: str
    patient_code: str
    date_of_birth: date | None
    biological_sex: str | None
    first_name: str | None
    last_name: str | None
    is_active: bool
    is_synthetic: bool
    notes: str | None
    created_at: datetime
    updated_at: datetime

    model_config = {"from_attributes": True}


class PatientListResponse(BaseModel):
    items: list[PatientResponse]
    total: int
    page: int
    page_size: int


@router.get("", response_model=PatientListResponse)
async def list_patients(
    current_user: CurrentUser,
    db: AsyncSession = Depends(get_db),
    page: int = Query(1, ge=1),
    page_size: int = Query(20, ge=1, le=100),
    search: str | None = None,
    biological_sex: str | None = None,
    include_archived: bool = False,
) -> Any:
    """List and search pseudonymous patient records with pagination."""
    query = select(Patient)

    if not include_archived:
        query = query.where(Patient.is_active.is_(True))

    if search:
        search_filter = f"%{search.strip()}%"
        query = query.where(
            or_(
                Patient.patient_code.ilike(search_filter),
                Patient.first_name.ilike(search_filter),
                Patient.last_name.ilike(search_filter),
            )
        )

    if biological_sex:
        query = query.where(Patient.biological_sex == biological_sex)

    # Count total
    count_query = select(func.count()).select_from(query.subquery())
    total = (await db.execute(count_query)).scalar() or 0

    # Paginate
    offset = (page - 1) * page_size
    query = query.order_by(Patient.created_at.desc()).offset(offset).limit(page_size)
    result = await db.execute(query)
    patients = result.scalars().all()

    return PatientListResponse(
        items=[
            PatientResponse(
                id=str(p.id),
                patient_code=p.patient_code,
                date_of_birth=p.date_of_birth,
                biological_sex=p.biological_sex,
                first_name=p.first_name,
                last_name=p.last_name,
                is_active=p.is_active,
                is_synthetic=p.is_synthetic,
                notes=p.notes,
                created_at=p.created_at,
                updated_at=p.updated_at,
            )
            for p in patients
        ],
        total=total,
        page=page,
        page_size=page_size,
    )


@router.post("", response_model=PatientResponse, status_code=status.HTTP_201_CREATED)
async def create_patient(
    request: Request,
    body: PatientCreate,
    current_user: CurrentUser,
    db: AsyncSession = Depends(get_db),
) -> Any:
    """Register a new patient record with a pseudonymous identifier."""
    # Autogenerate pseudonymous patient code if omitted (e.g. PAT-9A4B-83C1)
    patient_code = body.patient_code
    if not patient_code:
        rand_hex = secrets.token_hex(4).upper()
        patient_code = f"PAT-{rand_hex[:4]}-{rand_hex[4:]}"

    # Check for duplicate code
    existing = await db.execute(select(Patient).where(Patient.patient_code == patient_code))
    if existing.scalar_one_or_none():
        raise HTTPException(
            status_code=status.HTTP_409_CONFLICT,
            detail="A patient with this identifier already exists.",
        )

    new_patient = Patient(
        patient_code=patient_code,
        date_of_birth=body.date_of_birth,
        biological_sex=body.biological_sex,
        first_name=body.first_name,
        last_name=body.last_name,
        notes=body.notes,
        is_synthetic=body.is_synthetic,
        created_by_id=current_user.id,
        updated_by_id=current_user.id,
    )
    db.add(new_patient)
    await db.flush()

    await record_audit_event(
        db,
        action="patient.create",
        outcome="success",
        actor_id=current_user.id,
        actor_username=current_user.username,
        entity_type="patient",
        entity_id=new_patient.id,
        request=request,
    )
    await db.commit()

    return PatientResponse(
        id=str(new_patient.id),
        patient_code=new_patient.patient_code,
        date_of_birth=new_patient.date_of_birth,
        biological_sex=new_patient.biological_sex,
        first_name=new_patient.first_name,
        last_name=new_patient.last_name,
        is_active=new_patient.is_active,
        is_synthetic=new_patient.is_synthetic,
        notes=new_patient.notes,
        created_at=new_patient.created_at,
        updated_at=new_patient.updated_at,
    )


@router.get("/{patient_id}", response_model=PatientResponse)
async def get_patient(
    patient_id: uuid.UUID,
    current_user: CurrentUser,
    db: AsyncSession = Depends(get_db),
) -> Any:
    """Retrieve an individual patient profile."""
    result = await db.execute(select(Patient).where(Patient.id == patient_id))
    patient = result.scalar_one_or_none()
    if not patient:
        raise HTTPException(status_code=status.HTTP_404_NOT_FOUND, detail="Patient not found.")

    return PatientResponse(
        id=str(patient.id),
        patient_code=patient.patient_code,
        date_of_birth=patient.date_of_birth,
        biological_sex=patient.biological_sex,
        first_name=patient.first_name,
        last_name=patient.last_name,
        is_active=patient.is_active,
        is_synthetic=patient.is_synthetic,
        notes=patient.notes,
        created_at=patient.created_at,
        updated_at=patient.updated_at,
    )


@router.patch("/{patient_id}", response_model=PatientResponse)
async def update_patient(
    patient_id: uuid.UUID,
    body: PatientUpdate,
    request: Request,
    current_user: CurrentUser,
    db: AsyncSession = Depends(get_db),
) -> Any:
    """Update patient information."""
    result = await db.execute(select(Patient).where(Patient.id == patient_id))
    patient = result.scalar_one_or_none()
    if not patient:
        raise HTTPException(status_code=status.HTTP_404_NOT_FOUND, detail="Patient not found.")

    if body.date_of_birth is not None:
        patient.date_of_birth = body.date_of_birth
    if body.biological_sex is not None:
        patient.biological_sex = body.biological_sex
    if body.first_name is not None:
        patient.first_name = body.first_name
    if body.last_name is not None:
        patient.last_name = body.last_name
    if body.notes is not None:
        patient.notes = body.notes

    patient.updated_by_id = current_user.id
    await db.flush()

    await record_audit_event(
        db,
        action="patient.update",
        outcome="success",
        actor_id=current_user.id,
        actor_username=current_user.username,
        entity_type="patient",
        entity_id=patient.id,
        request=request,
    )
    await db.commit()

    return PatientResponse(
        id=str(patient.id),
        patient_code=patient.patient_code,
        date_of_birth=patient.date_of_birth,
        biological_sex=patient.biological_sex,
        first_name=patient.first_name,
        last_name=patient.last_name,
        is_active=patient.is_active,
        is_synthetic=patient.is_synthetic,
        notes=patient.notes,
        created_at=patient.created_at,
        updated_at=patient.updated_at,
    )


@router.delete(
    "/{patient_id}",
    status_code=status.HTTP_204_NO_CONTENT,
    response_class=Response,
    response_model=None,
)
async def archive_patient(
    patient_id: uuid.UUID,
    request: Request,
    current_user: CurrentUser,
    db: AsyncSession = Depends(get_db),
) -> None:
    """Soft archive patient record for audit retention."""
    result = await db.execute(select(Patient).where(Patient.id == patient_id))
    patient = result.scalar_one_or_none()
    if not patient:
        raise HTTPException(status_code=status.HTTP_404_NOT_FOUND, detail="Patient not found.")

    patient.is_active = False
    patient.archived_at = datetime.now(timezone.utc)
    patient.archived_by_id = current_user.id
    await db.flush()

    await record_audit_event(
        db,
        action="patient.archive",
        outcome="success",
        actor_id=current_user.id,
        actor_username=current_user.username,
        entity_type="patient",
        entity_id=patient.id,
        request=request,
    )
    await db.commit()


